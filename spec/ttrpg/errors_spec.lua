local errors = require("ttrpg.errors")

describe("ttrpg.errors", function()
    it("builds structured errors with code, message and details", function()
        local err = errors.new(errors.codes.NOT_FOUND, "missing", { id = "x" })
        assert.are.equal("NOT_FOUND", err.code)
        assert.are.equal("missing", err.message)
        assert.are.same({ id = "x" }, err.details)
        assert.are.equal("[NOT_FOUND] missing", tostring(err))
    end)

    it("rejects unknown codes", function()
        assert.has_error(function()
            errors.new("NOPE", "x")
        end)
    end)

    it("raise throws an error recognised by is()", function()
        local ok, err = pcall(errors.raise, errors.codes.PARSE_ERROR, "bad")
        assert.is_false(ok)
        assert.is_true(errors.is(err))
        assert.is_true(errors.is(err, errors.codes.PARSE_ERROR))
        assert.is_false(errors.is(err, errors.codes.NOT_FOUND))
    end)

    it("is() is false for plain values", function()
        assert.is_false(errors.is("boom"))
        assert.is_false(errors.is({ code = "NOT_FOUND" }))
        assert.is_false(errors.is(nil))
    end)

    describe("try", function()
        it("returns the result on success", function()
            local ok, value = errors.try(function(a, b)
                return a + b
            end, 2, 3)
            assert.is_true(ok)
            assert.are.equal(5, value)
        end)

        it("passes structured errors through", function()
            local ok, err = errors.try(errors.raise, errors.codes.NOT_FOUND, "gone")
            assert.is_false(ok)
            assert.are.equal("NOT_FOUND", err.code)
        end)

        it("wraps foreign errors as INTERNAL", function()
            local ok, err = errors.try(function()
                error("kaboom")
            end)
            assert.is_false(ok)
            assert.are.equal("INTERNAL", err.code)
            assert.matches("kaboom", err.message)
        end)
    end)
end)
